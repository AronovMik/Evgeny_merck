    j = rest.find('\n## Журнал изменений')
    tail = rest[j:] if j >= 0 else ''
    body = rest[:j] if j >= 0 else rest
    cards = re.split(r'(?m)(?=^## Аргумент )', body)
    cards = [c for c in cards if c.strip()]
    return head, cards, tail

