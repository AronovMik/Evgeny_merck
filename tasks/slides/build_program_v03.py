def add_heading(text, level=1):
    h = doc.add_heading(text, level=level)
    for run in h.runs:
        run.font.color.rgb = RGBColor(0x1F, 0x3A, 0x68)
    return h

def add_para(text, bold=False, italic=False, size=11, color=None, indent_cm=None):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color:
        run.font.color.rgb = color
    if indent_cm is not None:
        p.paragraph_format.left_indent = Cm(indent_cm)
    return p

def add_bullet(text, level=0):
    p = doc.add_paragraph(text, style='List Bullet' if level == 0 else 'List Bullet 2')
    return p

def add_clarify(text):
    """Yellow callout for 'Уточнить:' blocks."""
