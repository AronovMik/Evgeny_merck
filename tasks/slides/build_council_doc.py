def add_heading(text, level=1):
    h = doc.add_heading(text, level=level)
    for run in h.runs:
        run.font.color.rgb = RGBColor(0x1F, 0x3A, 0x68)
    return h


def add_para(text, bold=False, italic=False, size=11, color=None, indent_cm=None):
    p = doc.add_paragraph()
    run = p.add_run(text)
    run.font.size = Pt(size)
    run.bold = bold
    run.italic = italic
    if color:
        run.font.color.rgb = color
    if indent_cm is not None:
        p.paragraph_format.left_indent = Cm(indent_cm)
    return p


def add_bullet(text, level=0):
    return doc.add_paragraph(text, style='List Bullet' if level == 0 else 'List Bullet 2')


def add_banner(text, color_hex):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    pPr = p._p.get_or_add_pPr()
    shd = OxmlElement('w:shd')
    shd.set(qn('w:val'), 'clear')
    shd.set(qn('w:color'), 'auto')
    shd.set(qn('w:fill'), color_hex)
    pPr.append(shd)
    run = p.add_run(text)
    run.bold = True
    run.font.size = Pt(13)
    run.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)


def add_callout(label, text, color):
    p = doc.add_paragraph()
    p.paragraph_format.left_indent = Cm(0.5)
    r1 = p.add_run(f"{label}: ")
    r1.bold = True
    r1.font.color.rgb = color
    r2 = p.add_run(text)
    r2.italic = True
    r2.font.color.rgb = color
    return p


