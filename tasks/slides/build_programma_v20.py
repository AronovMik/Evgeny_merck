def H(t,l=1,c=NAVY):
    h=doc.add_heading(t,level=l)
    for r in h.runs: r.font.color.rgb=c
    return h
def P(t,b=False,i=False,sz=11,c=None):
    p=doc.add_paragraph(); r=p.add_run(t); r.bold=b; r.italic=i; r.font.size=Pt(sz)
